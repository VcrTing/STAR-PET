/// <summary>
/// 战斗能力类型枚举
/// 对应 InsFightPower.PowerType 字段，表示该能力影响哪种战斗能力
/// </summary>
public enum EnumFightPowerType
{
	RoundPriority = 1,   // 先手值：干预本回合/下回合出手顺序（数值正=提前，负=延后）
	ComboCount = 2,      // 连击数：技能额外追加的攻击次数
}
